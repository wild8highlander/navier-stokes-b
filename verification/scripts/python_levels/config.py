"""
config.py — единая константная цепочка точной редакции.

Каждая величина задана ЗАМКНУТОЙ ФОРМОЙ; численные значения получаются
из формы, а не подгоняются. α и L_min — константы теории Клейна из монографии
(цитируются с 50 знаками); их согласованность с b проверяется замыканием
Z_full/Z_leading = exp(b·β_K·L_min) на уровне L1.
"""

from mpmath import mp, mpf, pi, sqrt, asin, exp, log

MP_DIGITS = 50
mp.dps = MP_DIGITS

# ---- точные формы ----
B_FORM_POLY = lambda: pi / (4 * pi**2 + 2 * pi * sqrt(3))   # исходная форма монографии
B_FORM_SIMP = lambda: 1 / (4 * pi + 2 * sqrt(3))            # алгебраически эквивалентна

BETA_K = mpf(5) / 3                       # Колмогоров, 5/3
ALPHA_KLEIN = mpf("2.246979603717467061050009768008479621265")
L_MIN_KLEIN = mpf("2.898149445355172670064346286515453564939")
GAMMA_REF = mpf("0.95456")                # независимая оценка γ (монография, §4.5)
C_K_CAL = mpf("1.5")                      # калибровочное C_K

def constants():
    """Все константы в mp-точности (50 знаков)."""
    b = B_FORM_POLY()
    theta_b = asin(b)
    return {
        "b": b,
        "theta_b": theta_b,                       # рад
        "theta_b_deg": theta_b * 180 / pi,
        "cos_theta_b": sqrt(1 - b**2),            # тождество cos(arcsin b)=√(1-b²)
        "sin_minus_b": theta_b and (mp.sin(theta_b) - b),  # невязка ключевого тождества
        "ln_1p_b": log(1 + b),
        "Z_full_leading": exp(b * BETA_K * L_MIN_KLEIN),
        "Cs_lilly": (1 / pi) * (mpf(9) / 4) ** (-mpf(3) / 4),
        "phi": (1 + sqrt(5)) / 2,
        "e_klein": exp(1),
        "alpha_klein": ALPHA_KLEIN,
        "L_min_klein": L_MIN_KLEIN,
        "b_beta_L": b * BETA_K * L_MIN_KLEIN,
    }

